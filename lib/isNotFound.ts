/**
 * Ответил ли API «такой записи нет».
 *
 * Страницы показывают данные, полученные сервером, пока клиентский запрос не
 * ответит. Но серверная копия живёт в кэше до минуты: если запись за это время
 * удалили или сняли с публикации, клиент получит 404 — и тогда серверную копию
 * показывать нельзя. При сетевой ошибке, наоборот, она лучше пустого экрана.
 */
export function isNotFound(error: unknown): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    "status" in error &&
    (error as { status: unknown }).status === 404
  );
}
